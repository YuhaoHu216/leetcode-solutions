package F1016;

import java.util.Scanner;

/**
 * 小红的红黑数
 * 给出一个数组和一个字符串，数组由 n 个数字组成（每个数字介于 1 到 10^9），
 * 字符串仅由 'R' 和 'B' 组成，表示数组中对应下标的数字是红数还是黑数
 * （s[i] == 'R' 为红数，s[i] == 'B' 为黑数）。
 *
 * 【题目描述】
 * 一个"红黑组合"由数组中的一个红数和一个黑数构成，组合的值为这两个数的乘积。
 * 组合中两个数的先后顺序不作区分：同一个红数与同一个黑数组成的一对只算作一个组合。
 * 不同的红数与黑数两两之间都可以组成一个组合，
 * 例如第一个红数可以与每一个黑数各组成一个组合，第一个黑数也可以与每一个红数各组成一个组合。
 * 现在需要计算数组中所有红黑组合的乘积之和。由于数字过大，最终结果请对 (10^9 + 7) 取模。
 *
 * 【输入描述】
 * 第一行：一个整数 n，表示数组长度。
 * 第二行：n 个用空格分隔的整数 a[1] ... a[n]。
 * 第三行：一个长度为 n 的字符串 s，仅由 'R' 和 'B' 组成。
 *
 * 【输出描述】
 * 输出一个整数，表示所有红黑组合的乘积之和对 (10^9 + 7) 取模后的结果。
 * 若数组中不存在红数或不存在黑数（即无法组成任何红黑组合），输出 0。
 *
 * 【样例】
 * 输入：
 *   4
 *   1 2 3 4
 *   RBBR
 * 输出：
 *   25
 * 说明：
 *   红数为 1、4，黑数为 2、3。
 *   所有红黑组合为 (1,2)=2、(1,3)=3、(4,2)=8、(4,3)=12，
 *   乘积之和 = 2 + 3 + 8 + 12 = 25。
 *
 * 【数据范围】
 *   1 <= n <= 10000
 *   1 <= a[i] <= 10^9
 *   s 仅含 'R' 和 'B'，长度等于 n
 */
public class Question1 {
    private static final long MOD = 1_000_000_007L;

    public static void main(String[] args) {
        Scanner in = new Scanner(System.in);

        int n = in.nextInt();
        long[] a = new long[n];
        for (int i = 0; i < n; i++) {
            a[i] = in.nextLong();
        }
        String s = in.next();

        // 分别累加红数之和与黑数之和
        long sumR = 0, sumB = 0;
        for (int i = 0; i < n; i++) {
            if (s.charAt(i) == 'R') {
                sumR += a[i];
            } else {
                sumB += a[i];
            }
        }

        // 所有红黑组合的乘积之和 = (红数之和) * (黑数之和)
        // 某一颜色缺失时对应之和为 0，结果自然为 0
        long ans = (sumR % MOD) * (sumB % MOD) % MOD;
        System.out.println(ans);
    }
}